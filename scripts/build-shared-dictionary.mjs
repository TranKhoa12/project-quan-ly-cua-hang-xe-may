import {readFileSync,writeFileSync} from 'node:fs';
import {normalizePartText} from '../src/features/parts/catalog.ts';
const reference=JSON.parse(readFileSync('data/part-name-reference.json','utf8'));
const extra=JSON.parse(readFileSync('data/part-dictionary-extra.json','utf8'));
const names=[...reference.terms,...extra.names];
const terms=[...names.map(t=>({...t,kind:'name'})),...extra.categories.map(t=>({...t,kind:'category'})),...extra.brands.map(t=>({...t,kind:'brand'}))];
const keys=new Set();
for(const term of terms){const key=term.kind+':'+normalizePartText(term.name);if(keys.has(key)||!normalizePartText(term.name))throw Error('Duplicate/empty term '+key);keys.add(key);}
const q=value=>value==null?'NULL':"'"+value.replaceAll("'","''")+"'";
const rows=terms.map(t=>`(${q(t.kind)},${q(t.name)},ARRAY[${[...new Set(t.aliases)].sort().map(q).join(',')}]::text[],${q(t.category)},${q(t.source_url)})`);
const sql=`-- Shared reference dictionary only; never creates inventory, prices or transactions.
-- Generated by scripts/build-shared-dictionary.mjs. Keep applied migrations immutable.
BEGIN;
INSERT INTO public.part_terms AS existing(kind,name,aliases,category,source_url) VALUES
${rows.join(',\n')}
ON CONFLICT(kind,normalized_name) DO UPDATE SET
 aliases=ARRAY(SELECT DISTINCT a FROM unnest(existing.aliases||excluded.aliases) a ORDER BY a),
 category=coalesce(existing.category,excluded.category),
 source_url=coalesce(existing.source_url,excluded.source_url);
COMMIT;
`;
const target='supabase/migrations/202611050001_shared_part_dictionary.sql';
if(process.argv.includes('--check')){if(readFileSync(target,'utf8').replaceAll('\r\n','\n')!==sql)throw Error('Generated migration differs');}
else writeFileSync(target,sql);
console.log(JSON.stringify({names:names.length,categories:extra.categories.length,brands:extra.brands.length,aliases:terms.reduce((n,t)=>n+t.aliases.length,0)}));
